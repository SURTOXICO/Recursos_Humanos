    private void BTN_DesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_DesactivarActionPerformed
        if (txtidasistencia.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Seleccione una asistencia de la tabla.");

            return;
        }

        String sql = "UPDATE asistencia "
                + "SET estado = 'INACTIVO' "
                + "WHERE id_asistencia = ?";

        try (PreparedStatement ps = cn.prepareStatement(sql)) {

            ps.setInt(1,
                    Integer.parseInt(txtidasistencia.getText().trim()));

            ps.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "Asistencia dada de baja correctamente.");

            limpiarCampos();

            BTN_Modificar.setEnabled(false);
            BTN_Desactivar.setEnabled(false);

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Error al dar de baja: " + e.getMessage());

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "El ID debe ser numérico.");
        }
    }//GEN-LAST:event_BTN_DesactivarActionPerformed

    private void TXT_BuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TXT_BuscarKeyReleased
        String buscar = TXT_Buscar.getText().trim();

        DefaultTableModel modelo
                = (DefaultTableModel) JTABLE_Mantpermisolicencia.getModel();

        modelo.setRowCount(0);

        String sql = "SELECT id_asistencia, id_empleado, "
                + "id_estado_asistencia, fecha, hora_entrada, "
                + "hora_salida, observaciones "
                + "FROM asistencia "
                + "WHERE CAST(id_asistencia AS CHAR) LIKE ? "
                + "ORDER BY id_asistencia";

        try (PreparedStatement ps = cn.prepareStatement(sql)) {

            ps.setString(1, "%" + buscar + "%");

            try (ResultSet rs = ps.executeQuery()) {

                while (rs.next()) {

                    modelo.addRow(new Object[]{
                        rs.getInt("id_asistencia"),
                        rs.getInt("id_empleado"),
                        rs.getInt("id_estado_asistencia"),
                        rs.getDate("fecha"),
                        rs.getTime("hora_entrada"),
                        rs.getTime("hora_salida"),
                        rs.getString("observaciones")
                    });
                }
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Error al buscar asistencia: " + e.getMessage());
        }
    }//GEN-LAST:event_TXT_BuscarKeyReleased

