    private void JTABLE_MantpermisolicenciaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JTABLE_MantpermisolicenciaMouseClicked
        int fila = JTABLE_Mantpermisolicencia.getSelectedRow();

        if (fila >= 0) {

            txtidasistencia.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 0).toString());

            txtidempleado.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 1).toString());

            txtestadoasistencia.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 2).toString());

            Object fecha
                    = JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 3);

            if (fecha instanceof java.util.Date) {
                jDatefecha.setDate((java.util.Date) fecha);
            }

            txthoraentrada.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 4).toString());

            txthorasalida.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 5).toString());

            txtminutostardanza.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 6).toString());
            txtobservaciones.setText(
                    JTABLE_Mantpermisolicencia
                            .getValueAt(fila, 7).toString());
            BTN_Guardar.setEnabled(false);
            BTN_Modificar.setEnabled(true);
            BTN_Desactivar.setEnabled(true);
        }
    }//GEN-LAST:event_JTABLE_MantpermisolicenciaMouseClicked

