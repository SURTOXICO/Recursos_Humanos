    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed
        if (txtidempleado.getText().trim().isEmpty()
                || txtestadoasistencia.getText().trim().isEmpty()
                || txthoraentrada.getText().trim().isEmpty()
                || txthorasalida.getText().trim().isEmpty()
                || txtminutostardanza.getText().trim().isEmpty()
                || jDatefecha.getDate() == null) {

            JOptionPane.showMessageDialog(this,
                    "Complete todos los campos obligatorios.");

            return;
        }

        SimpleDateFormat formatoFecha
                = new SimpleDateFormat("yyyy-MM-dd");

        String fecha
                = formatoFecha.format(jDatefecha.getDate());

        String sql = "INSERT INTO asistencia "
                + "(id_empleado, id_estado_asistencia, fecha, "
                + "hora_entrada, hora_salida, observaciones) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        try (PreparedStatement ps = cn.prepareStatement(sql)) {

            ps.setInt(1,
                    Integer.parseInt(txtidempleado.getText().trim()));

            ps.setInt(2,
                    Integer.parseInt(txtestadoasistencia.getText().trim()));

            ps.setString(3, fecha);

            ps.setString(4,
                    txthoraentrada.getText().trim());

            ps.setString(5,
                    txthorasalida.getText().trim());

            ps.setString(6,
                    txtminutostardanza.getText().trim());

            ps.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "Asistencia registrada correctamente.");

            limpiarCampos();

            BTN_Guardar.setEnabled(false);

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Los IDs deben contener solamente números.");

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Error al guardar asistencia: " + e.getMessage());
        }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

