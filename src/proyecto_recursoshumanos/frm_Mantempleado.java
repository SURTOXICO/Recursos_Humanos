private void cargarTabla() {

    DefaultTableModel modelo =
            (DefaultTableModel)
            JTABLE_Mantempleadocapacitacion.getModel();

    modelo.setRowCount(0);

    String sql =
            "SELECT id_empleado, "
            + "id_tipo_documento, "
            + "id_genero, "
            + "id_profesion, "
            + "id_distrito, "
            + "numero_documento, "
            + "nombres, "
            + "apellidos, "
            + "telefono1, "
            + "telefono2, "
            + "fecha_nacimiento, "
            + "direccion_actual, "
            + "correo1, "
            + "correo2, "
            + "observaciones, "
            + "estado "
            + "FROM empleado "
            + "ORDER BY id_empleado";

    try {

        if (cn == null || cn.isClosed()) {

            Conexion_bd_Luis conexionBD =
                    new Conexion_bd_Luis();

            cn = conexionBD.conectar();
        }

        try (PreparedStatement ps =
                cn.prepareStatement(sql);
             ResultSet rs =
                ps.executeQuery()) {

            while (rs.next()) {

                modelo.addRow(new Object[]{

                    rs.getInt("id_empleado"),

                    rs.getInt("id_tipo_documento"),

                    rs.getInt("id_genero"),

                    rs.getInt("id_profesion"),

                    rs.getInt("id_distrito"),

                    rs.getString("numero_documento"),

                    rs.getString("nombres"),

                    rs.getString("apellidos"),

                    rs.getString("telefono1"),

                    rs.getString("telefono2"),

                    rs.getDate("fecha_nacimiento"),

                    rs.getString("direccion_actual"),

                    rs.getString("correo1"),

                    rs.getString("correo2"),

                    rs.getString("observaciones"),

                    rs.getString("estado")
                });
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al cargar empleados:\n"
                + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
