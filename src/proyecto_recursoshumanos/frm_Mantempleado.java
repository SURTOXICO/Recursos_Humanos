    private void TXT_BuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TXT_BuscarKeyReleased
    String buscar =
            TXT_Buscar.getText().trim();

    DefaultTableModel modelo =
            (DefaultTableModel)
            JTABLE_Mantempleadocapacitacion.getModel();

    modelo.setRowCount(0);

    String sql =
            "SELECT id_empleado, "
            + "id_tipo_documento, "
            + "id_genero, "
            + "id_profesion, "
            + "id_distrito, "
            + "numero_documento, "
            + "nombres, "
            + "apellidos, "
            + "telefono1, "
            + "telefono2, "
            + "fecha_nacimiento, "
            + "direccion_actual, "
            + "correo1, "
            + "correo2, "
            + "observaciones, "
            + "estado "
            + "FROM empleado "
            + "WHERE CAST(id_empleado AS CHAR) LIKE ? "
            + "OR numero_documento LIKE ? "
            + "OR nombres LIKE ? "
            + "OR apellidos LIKE ? "
            + "ORDER BY id_empleado";

    try (PreparedStatement ps =
            cn.prepareStatement(sql)) {

        String texto = "%" + buscar + "%";

        ps.setString(1, texto);
        ps.setString(2, texto);
        ps.setString(3, texto);
        ps.setString(4, texto);

        try (ResultSet rs =
                ps.executeQuery()) {

            while (rs.next()) {

                modelo.addRow(new Object[]{

                    rs.getInt("id_empleado"),
                    rs.getInt("id_tipo_documento"),
                    rs.getInt("id_genero"),
                    rs.getInt("id_profesion"),
                    rs.getInt("id_distrito"),
                    rs.getString("numero_documento"),
                    rs.getString("nombres"),
                    rs.getString("apellidos"),
                    rs.getString("telefono1"),
                    rs.getString("telefono2"),
                    rs.getDate("fecha_nacimiento"),
                    rs.getString("direccion_actual"),
                    rs.getString("correo1"),
                    rs.getString("correo2"),
                    rs.getString("observaciones"),
                    rs.getString("estado")
                });
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al buscar empleado:\n"
                + e.getMessage()
        );
    }
    }//GEN-LAST:event_TXT_BuscarKeyReleased

