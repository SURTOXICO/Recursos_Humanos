private void cargarTabla() {

    DefaultTableModel modelo =
            (DefaultTableModel)
            JTABLE_Mantempleadocapacitacion.getModel();

    modelo.setRowCount(0);

    String sql =
            "SELECT id_empleado_capacitacion, "
            + "id_capacitacion, "
            + "id_empleado, "
            + "estado_aprobacion, "
            + "nota_obtenida, "
            + "tiene_certificado "
            + "FROM empleado_capacitacion "
            + "ORDER BY id_empleado_capacitacion";

    try {

        if (cn == null || cn.isClosed()) {

            Conexion_bd_Luis conexionBD =
                    new Conexion_bd_Luis();

            cn = conexionBD.conectar();
        }

        try (PreparedStatement ps = cn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {

                modelo.addRow(new Object[]{

                    rs.getInt("id_empleado_capacitacion"),

                    rs.getInt("id_capacitacion"),

                    rs.getInt("id_empleado"),

                    rs.getString("estado_aprobacion"),

                    rs.getBigDecimal("nota_obtenida"),

                    rs.getString("tiene_certificado")
                });
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al cargar empleados capacitación:\n"
                + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

