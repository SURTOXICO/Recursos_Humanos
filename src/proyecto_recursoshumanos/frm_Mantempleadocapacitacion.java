    private void TXT_BuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TXT_BuscarKeyReleased
    String buscar =
            TXT_Buscar.getText().trim();

    DefaultTableModel modelo =
            (DefaultTableModel)
            JTABLE_Mantempleadocapacitacion.getModel();

    modelo.setRowCount(0);

    String sql =
            "SELECT id_empleado_capacitacion, "
            + "id_capacitacion, "
            + "id_empleado, "
            + "id_estado_aprobacion, "
            + "nota_obtenida, "
            + "tiene_certificado "
            + "FROM empleado_capacitacion "
            + "WHERE CAST(id_empleado_capacitacion AS CHAR) LIKE ? "
            + "ORDER BY id_empleado_capacitacion";

    try (PreparedStatement ps =
            cn.prepareStatement(sql)) {

        ps.setString(
                1,
                "%" + buscar + "%"
        );

        try (ResultSet rs =
                ps.executeQuery()) {

            while (rs.next()) {

                modelo.addRow(new Object[]{

                    rs.getInt(
                            "id_empleado_capacitacion"),

                    rs.getInt(
                            "id_capacitacion"),

                    rs.getInt(
                            "id_empleado"),

                    rs.getInt(
                            "id_estado_aprobacion"),

                    rs.getBigDecimal(
                            "nota_obtenida"),

                    rs.getString(
                            "tiene_certificado")
                });
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al buscar:\n"
                + e.getMessage()
        );
    }
    }//GEN-LAST:event_TXT_BuscarKeyReleased

