    private void JTABLE_MantempleadocapacitacionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JTABLE_MantempleadocapacitacionMouseClicked
    int fila =
            JTABLE_Mantempleadocapacitacion
                    .getSelectedRow();

    if (fila >= 0) {

        // ID EMPLEADO CAPACITACION
        txtidempleadocapacitacion.setText(
                JTABLE_Mantempleadocapacitacion
                        .getValueAt(fila, 0)
                        .toString()
        );

        // ID CAPACITACION
        txtidcapacitacion.setText(
                JTABLE_Mantempleadocapacitacion
                        .getValueAt(fila, 1)
                        .toString()
        );

        // ID EMPLEADO
        txtidempleado.setText(
                JTABLE_Mantempleadocapacitacion
                        .getValueAt(fila, 2)
                        .toString()
        );

        // ESTADO APROBACION
        txtidestadoaprobacion.setText(
                JTABLE_Mantempleadocapacitacion
                        .getValueAt(fila, 3)
                        .toString()
        );

        // NOTA OBTENIDA
        txtnotaobtenida.setText(
                JTABLE_Mantempleadocapacitacion
                        .getValueAt(fila, 4)
                        .toString()
        );

        // TIENE CERTIFICADO
        Object certificado =
                JTABLE_Mantempleadocapacitacion
                        .getValueAt(fila, 5);

        if (certificado != null) {

            txttienecertificado.setText(
                    certificado.toString()
            );

        } else {

            txttienecertificado.setText("");
        }

        BTN_Guardar.setEnabled(false);
        BTN_Modificar.setEnabled(true);
        BTN_Desactivar.setEnabled(true);
    }
    }//GEN-LAST:event_JTABLE_MantempleadocapacitacionMouseClicked

