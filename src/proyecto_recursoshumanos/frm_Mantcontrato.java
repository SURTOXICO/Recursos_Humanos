    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed
    if (txtidempleado.getText().trim().isEmpty()
            || txtidtipocontrato.getText().trim().isEmpty()
            || txtidcargo.getText().trim().isEmpty()
            || txtidsede.getText().trim().isEmpty()
            || txtidmodalidad.getText().trim().isEmpty()
            || txtsalario.getText().trim().isEmpty()
            || txthorassemanales.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Complete los campos obligatorios."
        );
        return;
    }

    if (jDatefechainicio.getDate() == null) {
        JOptionPane.showMessageDialog(
                this,
                "Seleccione la fecha de inicio."
        );
        return;
    }

    try {

        String sql = "INSERT INTO contrato "
                + "(id_empleado, id_tipo_contrato, id_cargo, id_sede, "
                + "id_modalidad, id_departamento_academico, salario, "
                + "horas_semanales, asignacion_familiar, fecha_inicio, "
                + "fecha_fin, detalles, observaciones, estado) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (PreparedStatement ps = cn.prepareStatement(sql)) {

            ps.setInt(1, Integer.parseInt(txtidempleado.getText()));
            ps.setInt(2, Integer.parseInt(txtidtipocontrato.getText()));
            ps.setInt(3, Integer.parseInt(txtidcargo.getText()));
            ps.setInt(4, Integer.parseInt(txtidsede.getText()));
            ps.setInt(5, Integer.parseInt(txtidmodalidad.getText()));

            if (txtiddepartamentoacademico.getText().trim().isEmpty()) {
                ps.setNull(6, java.sql.Types.INTEGER);
            } else {
                ps.setInt(6,
                        Integer.parseInt(txtiddepartamentoacademico.getText()));
            }

            ps.setBigDecimal(7,
                    new java.math.BigDecimal(txtsalario.getText()));

            ps.setInt(8,
                    Integer.parseInt(txthorassemanales.getText()));

            if (txtasignacionfamiliar.getText().trim().isEmpty()) {
                ps.setBigDecimal(
                        9,
                        java.math.BigDecimal.ZERO
                );
            } else {
                ps.setBigDecimal(
                        9,
                        new java.math.BigDecimal(
                                txtasignacionfamiliar.getText()
                        )
                );
            }

            SimpleDateFormat formato =
                    new SimpleDateFormat("yyyy-MM-dd");

            ps.setString(
                    10,
                    formato.format(jDatefechainicio.getDate())
            );

            if (jDatefechafin.getDate() == null) {
                ps.setNull(11, java.sql.Types.DATE);
            } else {
                ps.setString(
                        11,
                        formato.format(jDatefechafin.getDate())
                );
            }

            ps.setString(12, txtdetalles.getText());
            ps.setString(13, txtobservaciones.getText());

            if (txtestado.getText().trim().isEmpty()) {
                ps.setString(14, "ACTIVO");
            } else {
                ps.setString(14, txtestado.getText());
            }

            ps.executeUpdate();
        }

        limpiarCampos();

        BTN_Guardar.setEnabled(false);
        BTN_Modificar.setEnabled(false);
        BTN_Desactivar.setEnabled(false);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Los campos numéricos contienen valores incorrectos."
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al guardar el contrato: "
                + e.getMessage()
        );
    }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

