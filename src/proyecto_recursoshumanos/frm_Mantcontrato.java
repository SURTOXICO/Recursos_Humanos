    private void JTABLE_MantcontratoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JTABLE_MantcontratoMouseClicked
    int fila = JTABLE_Mantcontrato.getSelectedRow();

    if (fila == -1) {
        return;
    }

    txtidcontrato.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 0).toString()
    );

    txtidempleado.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 1).toString()
    );

    txtidtipocontrato.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 2).toString()
    );

    txtidcargo.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 3).toString()
    );

    txtidsede.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 4).toString()
    );

    txtidmodalidad.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 5).toString()
    );

    Object departamento =
            JTABLE_Mantcontrato.getValueAt(fila, 6);

    txtiddepartamentoacademico.setText(
            departamento == null ? "" : departamento.toString()
    );

    txtsalario.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 7).toString()
    );

    txthorassemanales.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 8).toString()
    );

    txtasignacionfamiliar.setText(
            JTABLE_Mantcontrato.getValueAt(fila, 9).toString()
    );

    Object fechaInicio =
            JTABLE_Mantcontrato.getValueAt(fila, 10);

    if (fechaInicio != null) {
        try {
            jDatefechainicio.setDate(
                    new SimpleDateFormat("yyyy-MM-dd")
                            .parse(fechaInicio.toString())
            );
        } catch (Exception e) {
            jDatefechainicio.setDate(null);
        }
    }

    Object fechaFin =
            JTABLE_Mantcontrato.getValueAt(fila, 11);

    if (fechaFin != null) {
        try {
            jDatefechafin.setDate(
                    new SimpleDateFormat("yyyy-MM-dd")
                            .parse(fechaFin.toString())
            );
        } catch (Exception e) {
            jDatefechafin.setDate(null);
        }
    } else {
        jDatefechafin.setDate(null);
    }

    Object detalles =
            JTABLE_Mantcontrato.getValueAt(fila, 12);

    txtdetalles.setText(
            detalles == null ? "" : detalles.toString()
    );

    Object observaciones =
            JTABLE_Mantcontrato.getValueAt(fila, 13);

    txtobservaciones.setText(
            observaciones == null ? "" : observaciones.toString()
    );

    Object estado =
            JTABLE_Mantcontrato.getValueAt(fila, 14);

    txtestado.setText(
            estado == null ? "" : estado.toString()
    );

    BTN_Guardar.setEnabled(false);
    BTN_Modificar.setEnabled(true);
    BTN_Desactivar.setEnabled(true);
    }//GEN-LAST:event_JTABLE_MantcontratoMouseClicked

