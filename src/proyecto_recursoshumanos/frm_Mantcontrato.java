private void cargarTabla() {

    DefaultTableModel modelo =
            (DefaultTableModel) JTABLE_Mantcontrato.getModel();

    modelo.setRowCount(0);

    String sql = "SELECT "
            + "id_contrato, "
            + "id_empleado, "
            + "id_tipo_contrato, "
            + "id_cargo, "
            + "id_sede, "
            + "id_modalidad, "
            + "id_departamento_academico, "
            + "salario, "
            + "horas_semanales, "
            + "asignacion_familiar, "
            + "fecha_inicio, "
            + "fecha_fin, "
            + "detalles, "
            + "observaciones, "
            + "estado "
            + "FROM contrato "
            + "ORDER BY id_contrato";

    try (PreparedStatement ps = cn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {

            modelo.addRow(new Object[]{
                rs.getInt("id_contrato"),
                rs.getInt("id_empleado"),
                rs.getInt("id_tipo_contrato"),
                rs.getInt("id_cargo"),
                rs.getInt("id_sede"),
                rs.getInt("id_modalidad"),
                rs.getInt("id_departamento_academico"),
                rs.getBigDecimal("salario"),
                rs.getInt("horas_semanales"),
                rs.getBigDecimal("asignacion_familiar"),
                rs.getDate("fecha_inicio"),
                rs.getDate("fecha_fin"),
                rs.getString("detalles"),
                rs.getString("observaciones"),
                rs.getString("estado")
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error al cargar contratos: " + e.getMessage()
        );
    }
}


